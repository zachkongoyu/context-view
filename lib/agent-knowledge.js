export function getTerm(slug) { return TERMS.find((term) => term.slug === slug); }
export function searchTerms(query = "", category = "all") {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return TERMS.filter((term) => {
    if (category !== "all" && term.category !== category) return false;
    const text = [term.name, ...term.aliases, term.summary, term.definition, term.boundary].join(" ").toLowerCase();
    return words.every((word) => text.includes(word));
  });
}

